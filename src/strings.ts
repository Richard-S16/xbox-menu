export type Language = "en" | "pt-BR";
export type Text = keyof typeof portuguese;

export function text(language: Language, key: Text, values: Record<string, string | number> = {}) {
  return (language === "pt-BR" ? portuguese[key] : key)
    .replace(/\{(\w+)\}/g, (token, name: string) => String(values[name] ?? token));
}
